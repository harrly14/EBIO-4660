// Precompiles views/client/**/*.hbs into one ES module the browser imports.
// Files under views/client/partials/ are also registered as Handlebars partials by name.
import fs from 'node:fs';
import path from 'node:path';
import Handlebars from 'handlebars';
import { listFiles, withoutExtension } from './files.js';

export function precompileClientTemplates(clientDir) {
  const entries = listFiles(clientDir, '.hbs').map(file => {
    const name = withoutExtension(file);
    const spec = Handlebars.precompile(fs.readFileSync(path.join(clientDir, file), 'utf8'), { strict: false });
    return `templates[${JSON.stringify(name)}] = Handlebars.template(${spec});`;
  });
  return [
    '// Generated by build/templates.js from views/client. Do not edit.',
    'const Handlebars = window.Handlebars;',
    'export const templates = {};',
    ...entries,
    "Object.keys(templates).filter(name => name.startsWith('partials/')).forEach(name => Handlebars.registerPartial(name.slice('partials/'.length), templates[name]));",
    ''
  ].join('\n');
}
